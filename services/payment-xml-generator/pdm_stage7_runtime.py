"""Controlled offline runtime entry point for the Stage 6 orchestrator.

Explicit manifest only. No generator invocation, source mutation or network calls.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
from lxml import etree
from pdm_stage6_orchestrator import build

class RuntimeError7(ValueError):
    pass

def run(manifest_path, xsd_dir, output_dir=None):
    manifest_path = Path(manifest_path)
    xsd_dir = Path(xsd_dir)
    if not manifest_path.is_file():
        raise RuntimeError7('manifest file missing')
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    schemas = []
    for name in ('pain.001.001.09.xsd', 'pain.002.001.12.xsd'):
        schemas.append(etree.XMLSchema(etree.parse(str(xsd_dir / name))))
    result = build(manifest, *schemas)
    messages = result['messages']
    # Only relative, fixed-format paths generated by the orchestrator are accepted.
    safe = re.compile(r'^(funding|wendi)/pain00[12]/[A-Za-z0-9_-]+\.xml$')
    for key in messages:
        if not safe.fullmatch(key):
            raise RuntimeError7('unsafe output path: ' + repr(key))
    report = {
        'mode': 'write' if output_dir is not None else 'validate-only',
        'manifest_sha256': hashlib.sha256(manifest_path.read_bytes()).hexdigest(),
        'counts': result['counts'],
        'message_count': len(messages),
        'message_sha256': {key: hashlib.sha256(value).hexdigest() for key, value in sorted(messages.items())},
        'funding_reconciliation': result['funding_reconciliation'],
    }
    if output_dir is not None:
        dest = Path(output_dir)
        if dest.exists() or dest.is_symlink():
            raise RuntimeError7('output destination already exists; refusing overwrite')
        if not dest.parent.is_dir():
            raise RuntimeError7('output parent directory missing')
        # Write to a private sibling and publish by rename, leaving no partial output.
        import tempfile
        import shutil
        temp = Path(tempfile.mkdtemp(prefix='.pdm-stage7-', dir=dest.parent))
        try:
            for key, payload in messages.items():
                target = temp / key
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(payload)
            (temp / 'audit.json').write_text(json.dumps(report, indent=2, sort_keys=True, default=str) + '\n', encoding='utf-8')
            if dest.exists() or dest.is_symlink():
                raise RuntimeError7('output destination appeared during processing')
            os.rename(temp, dest)
        finally:
            if temp.exists():
                shutil.rmtree(temp)
    return report

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', required=True, help='Explicit evidence manifest JSON; never inferred from loans')
    parser.add_argument('--xsd-dir', required=True)
    parser.add_argument('--write-output', help='Opt-in new output directory; never overwrites')
    args = parser.parse_args(argv)
    try:
        report = run(args.manifest, args.xsd_dir, args.write_output)
    except (ValueError, OSError, etree.XMLSyntaxError, etree.XMLSchemaParseError) as exc:
        parser.exit(1, 'FAIL: ' + str(exc) + '\n')
    print(json.dumps(report, indent=2, sort_keys=True, default=str))
    return 0

if __name__ == '__main__':
    sys.exit(main())
